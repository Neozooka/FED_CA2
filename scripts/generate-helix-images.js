const fs = require("fs");
const path = require("path");

const projectRoot = path.resolve(__dirname, "..");
const sourceDirectory = path.join(projectRoot, "images", "nexos-pro-helix");
const outputFile = path.join(projectRoot, "javascript", "helix-images.js");
const maxImages = 40;
const supportedExtensions = new Set([".avif", ".jpeg", ".jpg", ".png", ".webp"]);

const imageFiles = fs
    .readdirSync(sourceDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && supportedExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }))
    .slice(0, maxImages);

const imagePaths = imageFiles.map((fileName) => `../../images/nexos-pro-helix/${fileName}`);
const generated = `// Generated by scripts/generate-helix-images.js. Do not edit manually.\n` +
    `window.NEXOS_HELIX_IMAGES = Object.freeze(${JSON.stringify(imagePaths, null, 4)});\n`;

fs.writeFileSync(outputFile, generated);
console.log(`Generated ${imagePaths.length} unique helix image entries (maximum ${maxImages}).`);
